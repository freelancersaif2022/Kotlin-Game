package com.novacleaner.app.data

import android.content.Context
import android.content.pm.PackageManager
import android.os.Build
import android.os.Environment
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.flow.flow
import kotlinx.coroutines.flow.flowOn
import kotlinx.coroutines.currentCoroutineContext
import kotlinx.coroutines.ensureActive
import java.io.File

enum class JunkCategory(val title: String, val description: String) {
    CACHE("Cache files", "Temporary data apps keep on shared storage. Safe to remove – apps rebuild it."),
    THUMBNAILS("Thumbnails", "Preview images generated by galleries. Rebuilt automatically when needed."),
    TEMP("Temporary files", "Leftover .tmp files and unfinished downloads."),
    LOGS("Logs & crash reports", "Diagnostic files written by apps that are no longer needed."),
    APKS("Installation packages", "APK files. Packages of apps already installed are pre-selected."),
    EMPTY_FOLDERS("Empty folders", "Folders that contain nothing."),
}

data class JunkItem(
    val path: String,
    val name: String,
    val size: Long,
    val category: JunkCategory,
    val note: String? = null,
    val preselected: Boolean = true,
)

data class JunkScanState(
    val progress: Float = 0f,
    val currentPath: String = "",
    val scannedFiles: Int = 0,
    val foundBytes: Map<JunkCategory, Long> = emptyMap(),
    val items: List<JunkItem> = emptyList(),
    val done: Boolean = false,
)

object JunkScanner {

    private val cacheDirNames = setOf("cache", ".cache", "caches", "_cache", "cachefiles", "webviewcache", "imagecache", "image_cache")
    private val thumbDirNames = setOf(".thumbnails", "thumbnails", ".thumbs", "thumbs", ".thumb")
    private val tempDirNames = setOf("tmp", ".tmp", "temp", ".temp")
    private val logDirNames = setOf("log", "logs", ".log", ".logs", "crash", "crashes", "crashlogs", "xlog", "tombstones")
    private val tempExt = setOf("tmp", "temp", "part", "crdownload", "partial", "download", "bak", "old", "chk")
    private val logExt = setOf("log", "dmp", "mdmp", "trace", "anr", "xlog", "crash", "stacktrace")
    private val protectedTopLevel = setOf(
        "android", "dcim", "download", "downloads", "pictures", "music", "movies", "documents", "alarms",
        "ringtones", "notifications", "podcasts", "audiobooks", "recordings", "screenshots",
    )

    private fun dirCategory(name: String): JunkCategory? {
        val n = name.lowercase()
        return when (n) {
            in cacheDirNames -> JunkCategory.CACHE
            in thumbDirNames -> JunkCategory.THUMBNAILS
            in tempDirNames -> JunkCategory.TEMP
            in logDirNames -> JunkCategory.LOGS
            else -> null
        }
    }

    fun scan(context: Context): Flow<JunkScanState> = flow {
        val root = Environment.getExternalStorageDirectory()
        val items = ArrayList<JunkItem>()
        val found = JunkCategory.entries.associateWith { 0L }.toMutableMap()
        var scanned = 0
        var lastEmit = 0L
        val pm = context.packageManager

        fun record(item: JunkItem) {
            items += item
            found[item.category] = (found[item.category] ?: 0L) + item.size
        }

        // 1. This app's own caches.
        listOfNotNull(context.cacheDir, context.externalCacheDir).forEach { dir ->
            dir.listFiles()?.forEach { f ->
                val size = FileOps.sizeOf(f)
                if (size > 0) record(JunkItem(f.absolutePath, "Nova Cleaner • ${f.name}", size, JunkCategory.CACHE))
            }
        }

        val skip = buildSet {
            add(File(root, "Android/obb").absolutePath)
            if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.R) add(File(root, "Android/data").absolutePath)
        }
        val top = root.listFiles()?.sortedBy { it.name.lowercase() }.orEmpty()
        val totalTop = top.size.coerceAtLeast(1)

        top.forEachIndexed { index, topEntry ->
            currentCoroutineContext().ensureActive()
            val stack = ArrayDeque<Pair<File, Int>>()
            if (topEntry.isDirectory) stack.addLast(topEntry to 1) else classifyFile(topEntry, pm)?.let(::record)

            while (stack.isNotEmpty()) {
                val (dir, depth) = stack.removeLast()
                if (dir.absolutePath in skip || depth > 14) continue
                val children = dir.listFiles() ?: continue

                val category = dirCategory(dir.name)
                if (category != null && depth > 1) {
                    val size = children.sumOf { FileOps.sizeOf(it) }
                    scanned += children.size
                    if (size > 0) {
                        val parent = dir.parentFile?.name ?: ""
                        record(JunkItem(dir.absolutePath, "$parent/${dir.name}", size, category))
                    }
                    continue
                }
                if (children.isEmpty()) {
                    val isProtected = depth == 1 && dir.name.lowercase() in protectedTopLevel
                    if (!isProtected) record(JunkItem(dir.absolutePath, dir.name, 0L, JunkCategory.EMPTY_FOLDERS))
                    continue
                }
                for (child in children) {
                    if (child.isDirectory) {
                        stack.addLast(child to depth + 1)
                    } else {
                        scanned++
                        classifyFile(child, pm)?.let(::record)
                    }
                }
                val now = System.currentTimeMillis()
                if (now - lastEmit > 70) {
                    lastEmit = now
                    val inner = 1f - 1f / (1f + stack.size * 0.15f)
                    emit(
                        JunkScanState(
                            progress = ((index + inner * 0.9f) / totalTop).coerceIn(0f, 0.99f),
                            currentPath = dir.absolutePath.removePrefix(root.absolutePath).ifEmpty { "/" },
                            scannedFiles = scanned,
                            foundBytes = found.toMap(),
                        ),
                    )
                }
            }
            emit(
                JunkScanState(
                    progress = ((index + 1f) / totalTop).coerceAtMost(0.99f),
                    currentPath = "/${topEntry.name}",
                    scannedFiles = scanned,
                    foundBytes = found.toMap(),
                ),
            )
        }
        emit(JunkScanState(progress = 1f, scannedFiles = scanned, foundBytes = found.toMap(), items = items.toList(), done = true))
    }.flowOn(Dispatchers.IO)

    private fun classifyFile(file: File, pm: PackageManager): JunkItem? {
        val name = file.name
        val lower = name.lowercase()
        val ext = lower.substringAfterLast('.', "")
        val size = file.length()
        return when {
            lower.startsWith(".thumbdata") -> JunkItem(file.absolutePath, name, size, JunkCategory.THUMBNAILS)
            ext in tempExt || lower.startsWith("~$") -> if (size > 0) JunkItem(file.absolutePath, name, size, JunkCategory.TEMP) else null
            ext in logExt -> JunkItem(file.absolutePath, name, size, JunkCategory.LOGS)
            ext == "apk" -> {
                val meta = ApkInspector.inspect(pm, file.absolutePath)
                val installed = meta?.status == ApkStatus.INSTALLED || meta?.status == ApkStatus.OUTDATED
                JunkItem(
                    path = file.absolutePath,
                    name = meta?.label ?: name,
                    size = size,
                    category = JunkCategory.APKS,
                    note = meta?.status?.label ?: ApkStatus.DAMAGED.label,
                    preselected = installed || meta == null,
                )
            }
            else -> null
        }
    }
}
