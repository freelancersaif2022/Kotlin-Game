"""Tiny DSL used to author PyMaster course content.

Run ``python3.11 content-src/build.py`` to regenerate the JSON files in
app/src/main/assets/. Every code example is executed so the outputs shown
in the app are always real.
"""

import textwrap


def _clean(code):
    return textwrap.dedent(code).strip("\n") + "\n"


def T(text):
    """Paragraph. Supports `inline code` and **bold**."""
    return {"type": "text", "text": textwrap.dedent(text).strip()}


def H(text):
    return {"type": "heading", "text": text}


def TIP(text):
    return {"type": "tip", "text": textwrap.dedent(text).strip()}


def LI(*items):
    return {"type": "list", "items": list(items)}


def C(code, caption="", stdin=None, output=None):
    """Code example. Output is generated by running it unless ``output`` is given."""
    block = {"type": "code", "text": caption, "code": _clean(code)}
    block["_stdin"] = stdin or []
    if output is not None:
        block["output"] = output
    return block


def L(id, title, summary, blocks, keys=(), practice="", minutes=6):
    return {
        "id": id,
        "title": title,
        "summary": textwrap.dedent(summary).strip(),
        "minutes": minutes,
        "blocks": blocks,
        "keyPoints": list(keys),
        "practice": textwrap.dedent(practice).strip(),
    }


def Q(q, options, answer, explain="", code=""):
    return {"q": q, "code": _clean(code) if code else "", "options": options, "answer": answer, "explain": explain}


def M(id, number, title, subtitle, image, lessons, quiz):
    return {
        "id": id,
        "number": number,
        "title": title,
        "subtitle": subtitle,
        "image": image,
        "lessons": lessons,
        "quiz": quiz,
    }


def STEP(title, text, code=""):
    return {"title": title, "text": textwrap.dedent(text).strip(), "code": _clean(code) if code else ""}


def P(id, number, title, tagline, image, difficulty, minutes, overview, features, concepts, steps, code, stdin=()):
    return {
        "id": id,
        "number": number,
        "title": title,
        "tagline": tagline,
        "image": image,
        "difficulty": difficulty,
        "minutes": minutes,
        "overview": textwrap.dedent(overview).strip(),
        "features": features,
        "concepts": concepts,
        "steps": steps,
        "code": _clean(code),
        "_stdin": list(stdin),
    }
