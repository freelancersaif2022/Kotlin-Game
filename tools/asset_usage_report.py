#!/usr/bin/env python3
"""Static asset-usage report: which supplied sprite regions the game code references.

Region-name literals and string templates in core/src/main/kotlin are turned into patterns
("${...}" / "$name" become wildcards for one path segment). A region is *used* if a pattern names
it or one of its animations; button art counts per state actually wired (normal/pressed/disabled,
plus selected for toggle buttons). *Shared* regions are pixel-identical duplicates that the
pipeline stores once in the packed atlases. Writes docs/ASSET_USAGE.md.
"""
import json, os, re, sys
from collections import defaultdict

repo = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), ".."))
data = json.load(open(os.path.join(repo, "assets/data/sprites.json")))
regions = set(data["regions"])
anims = {k: v[2] for k, v in data["anims"].items()}

src = ""
for root, _, files in os.walk(os.path.join(repo, "core/src/main/kotlin")):
    for f in files:
        if f.endswith(".kt"):
            src += open(os.path.join(root, f)).read() + "\n"

prefixes = ("ui/", "effects/", "powerups/", "collectibles/", "environments/", "obstacles/", "characters/", "enemies/", "bosses/")
literals = set(m for m in re.findall(r'"([^"\n]*)"', src) if m.startswith(prefixes))
# enum-driven names: collectible animations, power-up ids, enemy/boss/player animation suffixes
for m in re.findall(r'"(collectibles/[a-z_]+/(?:spin|reward))"', src):
    literals.add(m)

def to_regex(lit):
    pat = re.sub(r"\$\{[^}]*\}|\$[A-Za-z_][A-Za-z0-9_]*", "\x00", lit)
    return re.compile("^" + re.escape(pat).replace("\x00", "[a-z0-9_]+") + "$")

patterns = [to_regex(l) for l in literals]
toggle_bases = set(re.findall(r'stateButton\("([^"]+)"[^)]*toggle = true', src))
STATES = ("normal", "pressed", "disabled", "selected")

used = {}
for name in sorted(anims):
    if any(p.match(name) for p in patterns):
        for fr in anims[name]:
            used.setdefault(fr, "animation " + name)
for r in sorted(regions):
    if r in used:
        continue
    if any(p.match(r) for p in patterns):
        used[r] = "direct reference"
        continue
    parent, _, last = r.rpartition("/")
    if last in STATES and any(p.match(parent) for p in patterns):
        if last != "selected" or parent in toggle_bases:
            used[r] = "button state"

# pixel-identical duplicates share one packed rect (same page + xy in the packed atlas)
shared = defaultdict(list)
atlas_dir = os.path.join(repo, "assets/atlas")
for f in os.listdir(atlas_dir):
    if not f.endswith(".atlas"):
        continue
    page = None; name = None
    for line in open(os.path.join(atlas_dir, f)):
        line = line.rstrip("\n")
        if line.endswith(".png"):
            page = line
        elif line and not line.startswith(" ") and ":" not in line:
            name = line
        elif line.strip().startswith("xy:") and name:
            shared[(page, line.strip())].append(name)
alias_groups = [v for v in shared.values() if len(v) > 1]
aliased = sum(len(v) - 1 for v in alias_groups)

REASONS = {
    "ui/gameplay/powerup_slot": "baked placeholder label \"POWERUP_SLOT\"; the HUD draws each power-up's own `hud` icon with a timer bar instead",
    "ui/gameover/ad_revive": "rewarded-ad art without an ad service: intentionally hidden (no fake ad button)",
    "ui/rewards/watch_ad": "rewarded-ad art without an ad service: intentionally hidden",
}
COMPONENT_REASON = "component whose baked heading is a placeholder (e.g. \"MISSION CARD\"); rows use the converted 9-patch panel with runtime text instead"

cat_total = defaultdict(int); cat_used = defaultdict(int)
def cat(r):
    p = r.split("/")
    return p[0] if p[0] != "ui" else "ui/" + p[1]
for r in regions:
    cat_total[cat(r)] += 1
    if r in used:
        cat_used[cat(r)] += 1

unused = sorted(r for r in regions if r not in used)
lines = ["# Asset usage report", "",
         "Generated by `python3 -I tools/asset_usage_report.py` from the game source and `assets/data/sprites.json`.", "",
         f"* Supplied sprite regions: **{len(regions)}** (animations: {len(anims)})",
         f"* Referenced by the game: **{len(used)}**",
         f"* Not referenced: **{len(unused)}**",
         f"* Shared (pixel-identical duplicates stored once in the packed atlases): **{aliased}** regions in {len(alias_groups)} groups", "",
         "Button art: `normal`, `pressed` and `disabled` are wired for every button; `selected` is shown only by toggle buttons "
         "(sound, music, vibration), so the other buttons' `selected` frames are listed as unused.", "",
         "| category | used | total |", "|---|---|---|"]
for c in sorted(cat_total):
    lines.append(f"| {c} | {cat_used[c]} | {cat_total[c]} |")
lines += ["", "## Not referenced", ""]
groups = defaultdict(list)
for r in unused:
    parent, _, last = r.rpartition("/")
    if last == "selected":
        groups["`selected` state of non-toggle buttons (no selected state in their UI)"].append(parent)
    elif r in REASONS:
        groups[REASONS[r]].append(r)
    elif parent in REASONS:
        groups[REASONS[parent]].append(r)
    elif r.startswith("ui/components/"):
        groups[COMPONENT_REASON].append(r)
    else:
        groups["other"].append(r)
for reason, items in groups.items():
    lines.append(f"* {reason}: " + ", ".join(f"`{i}`" for i in sorted(items)))
lines += ["", "Additional derived assets (not in the source pack): world preview thumbnails (`previews/*`) composited from each world's layers, "
          "the 9-patch region `ui/components/panel9` converted from `ui/components/panel.9.png`, bitmap fonts, launcher icons cropped from `ui/shop/card_max`, and all audio."]
out = os.path.join(repo, "docs", "ASSET_USAGE.md")
open(out, "w").write("\n".join(lines) + "\n")
print("\n".join(lines[:12]))
print("unused:", len(unused))
for k, v in groups.items():
    print(" ", k[:70], len(v))
