    fun byId(id: String) = all.firstOrNull { it.id == id }

    fun isUnlocked(project: Project, progress: Progress): Boolean {
        if (!Course.isCourseComplete(progress)) return false
        return project.number == 1 || all[project.number - 2].id in progress.completedProjects
    }

    fun progressOf(project: Project, progress: Progress): Float =
        progress.projectTasks[project.id].orEmpty().count { it in TASKS } / TASKS.size.toFloat()

